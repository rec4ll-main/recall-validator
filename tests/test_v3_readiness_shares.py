@pytest.mark.parametrize("demand_on", [True, False])
@pytest.mark.parametrize("readiness_mode", ["slots", "shares"])
@pytest.mark.parametrize("n", SIZES)
@pytest.mark.parametrize("kind", KINDS)
def test_bundle_row_cap_holds(kind, n, readiness_mode, demand_on):
    res = run_cohort(kind, n, False, demand_on, readiness_mode=readiness_mode)
    uids, w, owner, reason = _check_rows(res)
    assert reason is None and owner is None
    total = sum(w)
    cap = miner_cap(1.0, uids)
    assert all(v / total <= cap for v in w)
    assert res.unassigned_units == 0.0
    assert math.isclose(math.fsum(res.units_by_uid.values()), TOTAL_UNITS, abs_tol=TOL)


def test_bundle_row_cap_holds_over_evolution():
    for _, res in evolution(14, 10, False, readiness_mode="shares"):
        uids, _, owner, reason = _check_rows(res)
        assert reason is None and owner is None


