# ------------------------------------------------------------------ what-if tool

def _write_records(tmp_path, readiness_mode="shares"):
    """Synthetic records shaped like v3_runtime's for epochs 100..300."""
    d = tmp_path / "epochs"
    d.mkdir()
    state = None
    for i in range(3):
        miners = [_evo_miner(u, i) for u in range(1, 15)]
        demand = {n: 4.0 * w for n, w in DEMAND_W.items()}
        res = allocate_v3(miners, demand, state, 100 * (i + 1), readiness_mode=readiness_mode,
                          fallback_miners={m.uid: m.hotkey for m in miners})
        state = res.state
        rec = {
            "epoch_start_block": 100 * (i + 1), "readiness_split": 0.40,
            "readiness_mode": readiness_mode,
            "inputs": {"t_call": "2026-11-02T00:00:00Z", "demand": demand, "miners": [
                {"uid": m.uid, "hotkey": m.hotkey, "serious_failure": m.serious_failure,
                 "tiers": {t: {"factor": e.factor, "h_passes": e.h_passes, "h_n": e.h_n, "credited": e.credited,
                               "checks": [[c.name, c.n_eff, c.p_hat] for c in e.checks]}
                           for t, e in sorted(m.tiers.items())}} for m in miners]},
            "units_by_uid": {str(u): v for u, v in sorted(res.units_by_uid.items())},
            "unearned_by_reason": res.unearned_by_reason,
            "state_after": dict(res.state, generation_benchmark_policy_sha256=""),
        }
        if readiness_mode == "slots" and i == 2:
            del rec["readiness_mode"]  # pre-setting records carry no mode
        (d / f"{100 * (i + 1)}.json").write_text(json.dumps(rec))
    return d


@pytest.mark.parametrize("readiness_mode", ["slots", "shares"])
def test_whatif_reproduces_record_and_compares_modes(tmp_path, capsys, readiness_mode):
    import v3_whatif

    d = _write_records(tmp_path, readiness_mode)
    before = {p.name: p.read_bytes() for p in d.iterdir()}
    assert v3_whatif.main([str(d / "300.json"), "--json"]) == 0
    out = json.loads(capsys.readouterr().out)
    assert out["prev_record"].endswith("200.json")
    assert out["recorded_mode"] == readiness_mode
    assert out["max_abs_diff_vs_record"] == 0.0
    for m in ("slots", "shares"):
        t = out["totals"][m]
        assert math.isclose(t["paid"], TOTAL_UNITS, abs_tol=TOL)
        assert math.isclose(sum(r[m] for r in out["rows"]), t["paid"], abs_tol=TOL)
    # dedup survivors only (coldkeys of uids 1 and 13 collide -> uid 1 dropped)
    assert 1 not in {r["uid"] for r in out["rows"]}
    assert {p.name: p.read_bytes() for p in d.iterdir()} == before  # read-only
    # explicit --prev-record and the text table
    assert v3_whatif.main([str(d / "300.json"), "--prev-record", str(d / "200.json")]) == 0
    text = capsys.readouterr().out
    assert "slots" in text and "shares" in text and "unearned (redistributed) by reason" in text


