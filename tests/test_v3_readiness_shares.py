"""INCENTIVE_V3_READINESS_MODE: "shares" (default) and "slots" readiness payment.

* slots, chosen explicitly, reproduces the 604417f allocator exactly (golden digests in
  fixtures/v3_slots_golden_604417f.json, generated by running these scenarios against
  the 604417f tree);
* shares pays every tier-eligible miner R_t * q / max(sum q, K), never more than one
  slot's pay each, leaves the rest as readiness_unearned, and advances the slot table,
  stages and carry exactly as slots mode does;
* the bundle row cap holds through allocate_v3 -> encode_v3 -> owner_row ->
  validate_weight_rows in both readiness modes (never an owner row);
* the setting parses, rejects bad values and is accepted on gated mainnet netuid 31;
* epoch records name the mode; slaves verify shares bundles unchanged;
* v3_whatif recomputes a stored record under both modes.
"""

