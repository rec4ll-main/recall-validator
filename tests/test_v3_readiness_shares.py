# Shared with the golden generator: only APIs that exist at 604417f are used here.

def _canon(obj) -> bytes:
    return json.dumps(obj, sort_keys=True, separators=(",", ":"), allow_nan=False).encode()


def result_doc(res, earned_only: bool = True) -> dict:
    # The 604417f golden digests use that tree's field names: burn_units/burn_by_reason
    # were the earned-only remainder (now unassigned_units/unearned_by_reason), and
    # with redistribution only what no miner could take (now split equally).
    if earned_only:
        rest, rest_by_reason = res.unassigned_units, res.unearned_by_reason
    else:
        rest = res.equal_split_units
        rest_by_reason = {"verifier_cap": rest} if rest > 0 else {}
    return {
        "units_by_uid": {str(u): v for u, v in sorted(res.units_by_uid.items())},
        "burn_units": rest,
        "burn_by_reason": rest_by_reason,
        "redistributed_by_reason": res.redistributed_by_reason,
        "eligible": res.eligible, "holders": res.holders, "f": res.f,
        "events": res.events, "state": res.state,
    }


def result_digest(res, earned_only: bool = True) -> str:
    return hashlib.sha256(_canon(result_doc(res, earned_only))).hexdigest()


def _evo_miner(uid, epoch_i, reg_shift=0):
    """Miner whose per-tier quality drifts by epoch; some dip below the pass ratio."""
    tiers = {}
    for k, t in enumerate(TIERS):
        if (uid + k) % 3 == 0:
            continue
        wave = ((uid * 7 + epoch_i * 3 + k * 5) % 11) / 10.0
        p = NEED * 0.9 if (uid + epoch_i + k) % 7 == 0 else min(1.0, NEED + (1 - NEED) * wave)
        tiers[t] = MinerTierEvidence(
            checks=tuple(CheckStats(n, NEFF, p) for n in CHECKS_BY_TIER[t]),
            factor=0.6 + 0.4 * ((uid + k) % 5) / 4, h_passes=60 + (uid * 13 + epoch_i) % 40, h_n=100,
            credited={n: float(10 + (uid * 3 + epoch_i) % 17) for n in ("vdb_query", "emb", "rerank", "gen")})
    return MinerEvidence(uid=uid, hotkey=f"5e{uid}", coldkey=f"5ck{uid % 12}",
                         registration_block=1000 + uid + reg_shift, tiers=tiers,
                         serious_failure=(uid == 4 and epoch_i == 6))


def evolution(n_miners, epochs, earned_only, **kw):
    """Run ``epochs`` epochs from an empty state; yields (epoch, result) per epoch."""
    state = None
    for i in range(epochs):
        miners = [_evo_miner(u, i, reg_shift=50 if (u == 3 and i >= 5) else 0) for u in range(1, n_miners + 1)]
        demand = {n: (i + 1) * 2.0 * w for n, w in DEMAND_W.items()} if i % 2 else {}
        everyone = {m.uid: m.hotkey for m in miners}
        res = allocate_v3(miners, demand, state, 100 * (i + 1), redistribute=not earned_only,
                          fallback_miners=everyone, **kw)
        state = res.state
        yield 100 * (i + 1), res


def cohort_cases():
    for kind in KINDS:
        for n in SIZES:
            for earned_only in (True, False):
                for demand_on in (True, False):
                    yield f"{kind}/{n}/{int(earned_only)}/{int(demand_on)}", kind, n, earned_only, demand_on


def run_cohort(kind, n, earned_only, demand_on, **kw):
    miners = _cohort(kind, n)
    demand = {name: 10 * w for name, w in DEMAND_W.items()} if demand_on else {}
    return allocate_v3(miners, demand, _state(miners, demand_on), 200, redistribute=not earned_only,
                       fallback_miners={m.uid: m.hotkey for m in miners}, **kw)


EVOLUTIONS = [(6, 10), (14, 10)]


def golden_doc(**kw) -> dict:
    out = {}
    for name, kind, n, b, d in cohort_cases():
        out[f"cohort/{name}"] = result_digest(run_cohort(kind, n, b, d, **kw), b)
    for n_miners, epochs in EVOLUTIONS:
        for b in (True, False):
            for epoch, res in evolution(n_miners, epochs, b, **kw):
                out[f"evo/{n_miners}/{int(b)}/{epoch}"] = result_digest(res, b)
    return out


