"""Golden pin of the production master configuration (score_version 11).

Production runs incentive v3 weights with INCENTIVE_V3_READINESS_MODE=shares,
INCENTIVE_V3_BURN_UNEARNED=false (no-burn redistribution) and
INCENTIVE_V3_READINESS_SPLIT=0.40. ``fixtures/v3_production_golden.json`` was
generated by this module from the code at recall-validator 910044e, before the
legacy score paths were removed. Any change to the signed payload, the persisted
epoch records or allocator state for this configuration fails here. The fixture
must never be regenerated from this or a later build.

sr25519 signatures are randomized, so the envelope is compared field by field
except the signature, which must verify against the master hotkey instead.
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import replace
from pathlib import Path
from types import SimpleNamespace

import bundle_consume
from bundle_consume import slave_consume
from bundle_ipfs import IpfsError, compute_raw_cid
from bundle_schedule import PUBLICATION_CUTOFF_BLOCKS
from bundle_v2 import parse_bundle
from chain_v2_fake import (
    HOTKEYS, MASTER, MINERS, SLAVE, FakeChain, FakeMetagraph, FakeSubtensor, FakeWallet,
    config, publish_pointer,
)
from v3_metrics_client import parse_v3_metrics

FIXTURES = Path(__file__).parent / "fixtures"
EVIDENCE = FIXTURES / "recall_v3_metrics_fixture.json"
GOLDEN = FIXTURES / "v3_production_golden.json"
EPOCHS = (3600, 3960, 4320, 4680)
PRODUCTION = {"v3_readiness_mode": "shares", "v3_burn_unearned": False, "v3_readiness_split": 0.40}


def _body(epoch, netuid):
    body = json.loads(EVIDENCE.read_text())["body"]
    body["netuid"], body["epoch_start_block"] = netuid, epoch
    for i, m in enumerate(body["miners"]):
        m["hotkey"] = MINERS[i].ss58_address
    return body


def _sha(raw: bytes) -> str:
    return hashlib.sha256(raw).hexdigest()


def compute_golden(tmp_path, monkeypatch) -> dict:
    import v3_runtime
    from bundle_envelope import build_envelope

    chain = FakeChain()
    sub = FakeSubtensor(chain)
    blocks: dict[str, bytes] = {}

    def fake_fetch(api_url, cid, **kw):
        data = blocks.get(cid)
        if data is None or compute_raw_cid(data) != cid:
            raise IpfsError("IPFS HTTP 404")
        return data

    def evidence(api_url, key, cohort, netuid, epoch, allow_plaintext=False):
        return parse_v3_metrics(_body(epoch, netuid), netuid, epoch, {h: u for u, h in cohort})

    monkeypatch.setattr(bundle_consume, "fetch_block", fake_fetch)
    monkeypatch.setattr(bundle_consume, "fetch_gateway", fake_fetch)
    monkeypatch.setattr(v3_runtime, "fetch_v3_metrics", evidence)

    def cfg(role):
        c = config(tmp_path / role, ipfs_api_url="http://127.0.0.1:5001", role=role)
        return replace(c, api_url="https://api.test", internal_api_key="k", **PRODUCTION)

    master_cfg, slave_cfg = cfg("master"), cfg("slave")
    slave_uid = HOTKEYS.index(SLAVE.ss58_address)
    out = {}
    for e in EPOCHS:
        chain.advance_to(e + 5)
        schedule = SimpleNamespace(epoch_start_block=e, subnet_epoch_index=e // chain.tempo,
                                   cutoff_block=e + PUBLICATION_CUTOFF_BLOCKS)
        envelope = build_envelope(sub, FakeMetagraph(), FakeWallet(MASTER), master_cfg, schedule, fetch=None)
        parsed = parse_bundle(envelope)  # verifies the signature against master_hotkey
        assert parsed.payload.master_hotkey == MASTER.ss58_address
        wire = json.loads(envelope)
        assert set(wire) == {"payload", "signature"}
        blocks[publish_pointer(chain, envelope, e + 5)] = envelope
        chain.advance_to(e + 20)
        consumed = slave_consume(sub, FakeMetagraph(), FakeWallet(SLAVE), slave_cfg)
        assert consumed.status == "applied", consumed
        applied = [row for _, uid, row in chain.applied_weight_sets if uid == slave_uid][-1]
        root = Path(master_cfg.state_dir)
        files = {str(p.relative_to(root)): _sha(p.read_bytes())
                 for sub_dir in ("v3", "v3_eligibility", "v3_artifact_policies")
                 for p in sorted((root / sub_dir).rglob("*")) if p.is_file()}
        out[str(e)] = {
            "payload": wire["payload"],
            "payload_sha256": _sha(json.dumps(wire["payload"], sort_keys=True,
                                              separators=(",", ":")).encode()),
            "slave_applied": [list(x) for x in applied],
            "v3_state_files_sha256": files,
        }
    return out


def test_production_configuration_is_byte_identical(tmp_path, monkeypatch):
    golden = json.loads(GOLDEN.read_text())
    assert golden["source_commit"] == "910044e"
    assert golden["configuration"] == {"readiness_mode": "shares", "burn_unearned": False,
                                       "readiness_split": 0.40}
    got = compute_golden(tmp_path, monkeypatch)
    assert list(got) == list(golden["epochs"])
    for epoch, want in golden["epochs"].items():
        have = got[epoch]
        assert have["payload"] == want["payload"], epoch
        assert have["payload_sha256"] == want["payload_sha256"], epoch
        assert have["slave_applied"] == want["slave_applied"], epoch
        assert have["v3_state_files_sha256"] == want["v3_state_files_sha256"], epoch

